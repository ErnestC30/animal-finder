import { fileURLToPath, URL } from 'node:url'
import tailwindcss from '@tailwindcss/vite'
import react from '@vitejs/plugin-react'
import { defineConfig } from 'vite'

// https://vite.dev/config/
export default defineConfig({
  plugins: [react(), tailwindcss()],
  resolve: {
    alias: {
      '@': fileURLToPath(new URL('./src', import.meta.url)),
    },
  },
  server: {
    proxy: {
      // Forward /api/* to the FastAPI backend, e.g. /api/chat/stream -> /chat/stream
      '/api': {
        // 127.0.0.1, not localhost: on Windows localhost tries IPv6 ::1 first and
        // waits for that to fail before falling back to IPv4, where uvicorn listens
        target: 'http://127.0.0.1:8000',
        changeOrigin: true,
        rewrite: (path) => path.replace(/^\/api/, ''),
      },
    },
  },
})
